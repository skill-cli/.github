#!/usr/bin/env python3
"""Render the organization profile from its catalog."""

import argparse
import difflib
import html
import json
from pathlib import Path
import re
import sys
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]


def render_summary(summary):
    escaped = html.escape(summary)
    return re.sub(r"`([^`\n]+)`", r"<code>\1</code>", escaped)


def render(catalog):
    commands = catalog["quickstart"]["commands"]
    for index, command in enumerate(commands):
        if "\n" in command or "\r" in command:
            raise ValueError(f"quickstart.commands[{index}] must be a single line")
        if "```" in command:
            raise ValueError(f"quickstart.commands[{index}] must not contain three consecutive backticks")
    organization = html.escape(catalog["organization"])
    promise = catalog["promise"]
    mark = catalog["mark"]
    mark_base = f"https://raw.githubusercontent.com/{organization}/.github/master/"
    mark_path = quote(mark["path"], safe="/") if "dark" in mark else html.escape(mark["path"])
    mark_lines = [
        f'<img src="{mark_base}{mark_path}" '
        f'width="128" alt="{html.escape(mark["alt"])}">'
    ]
    if "dark" in mark:
        mark_lines = [
            "<picture>",
            f'<source media="(prefers-color-scheme: dark)" '
            f'srcset="{mark_base}{quote(mark["dark"], safe="/")}">',
            *mark_lines,
            "</picture>",
        ]
    navigation = " · ".join(
        f'<a href="{html.escape(link["url"])}">{html.escape(link["title"])}</a>'
        for link in catalog["navigation"]
    )
    lines = [
        "<!-- Generated by Scripts/render-profile.py from profile/catalog.json. -->",
        "",
        '<div align="center">',
        *mark_lines,
        f'<h1>{html.escape(promise["heading"])}</h1>',
        f'<p>{html.escape(promise["secondary"])}</p>',
        f"<p>{navigation}</p>",
        "</div>",
        "",
        f'### {html.escape(catalog["quickstart"]["title"])}',
        "",
        "```sh",
        *commands,
        "```",
    ]
    for group in catalog["groups"]:
        lines.extend(["", f'### {html.escape(group["title"])}', "", "<table>"])
        for repository in group["repositories"]:
            name = html.escape(repository["name"])
            summary = render_summary(repository["summary"])
            lines.append(
                f'<tr><td><strong><a href="https://github.com/{organization}/{name}">'
                f"{name}</a></strong><br>{summary}</td></tr>"
            )
        lines.append("</table>")
    return "\n".join(lines) + "\n"


def main(argv=None, *, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)
    try:
        catalog = json.loads((root / "profile/catalog.json").read_text(encoding="utf-8"))
        expected = render(catalog).encode("utf-8")
        destination = root / "profile/README.md"
        if not args.check:
            destination.write_bytes(expected)
            return 0
        actual = destination.read_bytes() if destination.exists() else b""
        if actual == expected:
            return 0
        for line in difflib.unified_diff(
            actual.decode("utf-8").splitlines(keepends=True),
            expected.decode("utf-8").splitlines(keepends=True),
            fromfile="profile/README.md",
            tofile="profile/README.md (generated)",
        ):
            sys.stdout.write(line)
            if not line.endswith("\n"):
                sys.stdout.write("\n\\ No newline at end of file\n")
        return 1
    except (OSError, UnicodeError, ValueError, KeyError, TypeError) as error:
        print(f"Cannot render profile: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
