# Keep test imports from creating unignored bytecode beside repository sources.
sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]


def load_script(name, filename):
    loader = importlib.machinery.SourceFileLoader(name, str(ROOT / "Scripts" / filename))
    spec = importlib.util.spec_from_loader(name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


renderer = load_script("render_profile", "render-profile.py")
checks = load_script("profile_checks", "check")


def committed_catalog():
    return json.loads((ROOT / "profile/catalog.json").read_text(encoding="utf-8"))


def repository(name, *, archived=False, private=False):
    return {"name": name, "archived": archived, "private": private}


class Response(io.BytesIO):
    def __init__(self, payload, link=""):
        super().__init__(json.dumps(payload).encode("utf-8"))
        self.headers = {"Link": link}


class RenderingTests(unittest.TestCase):
    def test_committed_catalog_is_deterministic_and_current(self):
        catalog = committed_catalog()
        rendered = renderer.render(catalog).encode("utf-8")
        reordered = json.loads(json.dumps(catalog, sort_keys=True))
        self.assertEqual(rendered, renderer.render(reordered).encode("utf-8"))
        self.assertEqual(rendered, (ROOT / "profile/README.md").read_bytes())
        self.assertTrue(rendered.endswith(b"\n"))
        self.assertFalse(rendered.endswith(b"\n\n"))

    def test_layout_and_order(self):
        catalog = {
            "organization": "example",
            "mark": {"path": "profile/mark.png", "alt": "Example mark"},
            "promise": {"heading": "Heading", "secondary": "Secondary"},
            "navigation": [
                {"title": "Docs", "url": "https://example.com/docs"},
                {"title": "Help", "url": "https://example.com/help"},
            ],
            "quickstart": {"title": "Start", "commands": ["first", "second"]},
            "groups": [
                {"title": "Tools", "repositories": [{"name": "tool", "summary": "Use `tool`."}]},
                {"title": "More", "repositories": [{"name": "other", "summary": "Another tool."}]},
            ],
        }
        self.assertEqual(renderer.render(catalog), '''<!-- Generated by Scripts/render-profile.py from profile/catalog.json. -->

<div align="center">
<img src="https://raw.githubusercontent.com/example/.github/master/profile/mark.png" width="128" alt="Example mark">
<h1>Heading</h1>
<p>Secondary</p>
<p><a href="https://example.com/docs">Docs</a> · <a href="https://example.com/help">Help</a></p>
</div>

### Start

```sh
first
second
```

### Tools

<table>
<tr><td><strong><a href="https://github.com/example/tool">tool</a></strong><br>Use <code>tool</code>.</td></tr>
</table>

### More

<table>
<tr><td><strong><a href="https://github.com/example/other">other</a></strong><br>Another tool.</td></tr>
</table>
''')

    def test_all_rendered_catalog_text_is_html_escaped(self):
        raw = '<tag> & "quote" \'single\''
        escaped = '&lt;tag&gt; &amp; &quot;quote&quot; &#x27;single&#x27;'

        def replace_text(value):
            if isinstance(value, dict):
                return {key: replace_text(item) for key, item in value.items()}
            if isinstance(value, list):
                return [replace_text(item) for item in value]
            return raw

        rendered = renderer.render(replace_text(committed_catalog()))
        self.assertNotIn(raw, rendered)
        for fragment in (
            f'/{escaped}/.github/master/{escaped}" width="128" alt="{escaped}"',
            f"<h1>{escaped}</h1>", f"<p>{escaped}</p>",
            f'<a href="{escaped}">{escaped}</a>', f"### {escaped}",
            f"```sh\n{escaped}\n", f'/{escaped}/{escaped}">{escaped}</a>',
            f"<br>{escaped}</td>",
        ):
            with self.subTest(fragment=fragment):
                self.assertIn(fragment, rendered)

    def test_summary_code_spans_escape_contents_and_preserve_unmatched_backticks(self):
        self.assertEqual(
            renderer.render_summary('Run `<script>&"` then `skill` & leave `open.'),
            'Run <code>&lt;script&gt;&amp;&quot;</code> then <code>skill</code> &amp; leave `open.',
        )
        self.assertEqual(renderer.render_summary("`one\ntwo`"), "`one\ntwo`")


class RenderCommandTests(unittest.TestCase):
    def setUp(self):
        self.root = ROOT / ".build/test-profile"
        self.root.mkdir(parents=True)
        self.addCleanup(shutil.rmtree, self.root)
        (self.root / "profile").mkdir()
        (self.root / "profile/catalog.json").write_text(
            json.dumps(committed_catalog()), encoding="utf-8"
        )
        self.destination = self.root / "profile/README.md"
        self.expected = renderer.render(committed_catalog()).encode("utf-8")

    def run_check(self):
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            status = renderer.main(["--check"], root=self.root)
        return status, output.getvalue()

    def test_write_generates_utf8_bytes(self):
        self.assertEqual(renderer.main([], root=self.root), 0)
        self.assertEqual(self.destination.read_bytes(), self.expected)

    def test_check_equal_writes_nothing(self):
        self.destination.write_bytes(self.expected)
        before = self.destination.stat().st_mtime_ns
        self.assertEqual(self.run_check(), (0, ""))
        self.assertEqual(self.destination.stat().st_mtime_ns, before)

    def test_check_drift_prints_unified_diff_without_writing(self):
        self.destination.write_bytes(b"outdated\n")
        before = self.destination.stat().st_mtime_ns
        status, output = self.run_check()
        self.assertEqual(status, 1)
        self.assertTrue(output.startswith("--- profile/README.md\n+++ profile/README.md (generated)\n@@"))
        self.assertIn("-outdated\n", output)
        self.assertIn("+<!-- Generated", output)
        self.assertEqual(self.destination.read_bytes(), b"outdated\n")
        self.assertEqual(self.destination.stat().st_mtime_ns, before)

    def test_check_missing_output_does_not_create_it(self):
        status, output = self.run_check()
        self.assertEqual(status, 1)
        self.assertIn("+<!-- Generated", output)
        self.assertFalse(self.destination.exists())

    def test_check_detects_byte_level_newline_drift(self):
        for actual in (self.expected[:-1], self.expected + b"\n", self.expected.replace(b"\n", b"\r\n")):
            with self.subTest(actual=actual[-20:]):
                self.destination.write_bytes(actual)
                status, output = self.run_check()
                self.assertEqual(status, 1)
                self.assertIn("@@", output)
                self.assertEqual(self.destination.read_bytes(), actual)


class CatalogValidationTests(unittest.TestCase):
    def test_committed_catalog_is_valid(self):
        checks.validate_catalog(committed_catalog())

    def test_required_fields_are_present_nonempty_and_correctly_typed(self):
        string_paths = [
            ("organization",), ("promise", "heading"), ("promise", "secondary"),
            ("promise", "description"), ("mark", "path"), ("mark", "alt"),
            ("navigation", 0, "title"), ("navigation", 0, "url"),
            ("quickstart", "title"), ("groups", 0, "title"),
            ("groups", 0, "repositories", 0, "name"),
            ("groups", 0, "repositories", 0, "summary"),
        ]
        container_paths = [
            ("promise",), ("mark",), ("navigation",), ("quickstart",),
            ("quickstart", "commands"), ("groups",), ("groups", 0, "repositories"),
        ]
        for path in string_paths + container_paths:
            for replacement in (None, "", "  ", [], {}, 42):
                with self.subTest(path=path, replacement=replacement):
                    catalog = copy.deepcopy(committed_catalog())
                    parent = catalog
                    for key in path[:-1]:
                        parent = parent[key]
                    if replacement is None:
                        del parent[path[-1]]
                    else:
                        parent[path[-1]] = replacement
                    with self.assertRaises(ValueError):
                        checks.validate_catalog(catalog)

    def test_invalid_list_entries_and_commands(self):
        cases = [
            ("navigation", [None]), ("groups", [None]),
            ("quickstart", {"title": "Start", "commands": [""]}),
            ("quickstart", {"title": "Start", "commands": ["first\nsecond"]}),
            ("groups", [{"title": "Tools", "repositories": [None]}]),
        ]
        for key, value in cases:
            with self.subTest(key=key, value=value):
                catalog = committed_catalog()
                catalog[key] = value
                with self.assertRaises(ValueError):
                    checks.validate_catalog(catalog)
        with self.assertRaises(ValueError):
            checks.validate_catalog([])

    def test_urls_require_https_and_host(self):
        for url in ("http://example.com", "javascript:alert(1)", "//example.com", "https://", "https://[broken"):
            with self.subTest(url=url):
                catalog = committed_catalog()
                catalog["navigation"][0]["url"] = url
                with self.assertRaises(ValueError):
                    checks.validate_catalog(catalog)

    def test_duplicate_repositories_across_groups(self):
        catalog = committed_catalog()
        duplicate = copy.deepcopy(catalog["groups"][0]["repositories"][0])
        duplicate["name"] = duplicate["name"].upper()
        catalog["groups"][1]["repositories"].append(duplicate)
        with self.assertRaisesRegex(ValueError, "duplicate repository name"):
            checks.validate_catalog(catalog)

    def test_mark_requires_existing_repository_file(self):
        for path in ("profile/missing.png", "profile", "../outside.png", str(ROOT / "README.md")):
            with self.subTest(path=path):
                catalog = committed_catalog()
                catalog["mark"]["path"] = path
                with self.assertRaisesRegex(ValueError, "mark.path"):
                    checks.validate_catalog(catalog)


class MembershipTests(unittest.TestCase):
    def setUp(self):
        self.catalog = committed_catalog()
        self.repositories = [
            repository(item["name"])
            for group in self.catalog["groups"] for item in group["repositories"]
        ]

    def test_matching_membership_excludes_archived_private_and_profile(self):
        checks.compare_membership(self.catalog, self.repositories + [
            repository(".github"), repository("old", archived=True), repository("secret", private=True),
        ])

    def test_missing_and_extra_are_reported_together(self):
        expected_extra = self.repositories[0]["name"]
        with self.assertRaisesRegex(
            ValueError, f"missing from catalog: alpha, zeta; extra in catalog: {expected_extra}"
        ):
            checks.compare_membership(self.catalog, self.repositories[1:] + [repository("zeta"), repository("alpha")])

    def test_archived_or_profile_in_catalog_is_extra(self):
        for name, archived in (("old", True), (".github", False)):
            with self.subTest(name=name):
                catalog = copy.deepcopy(self.catalog)
                catalog["groups"][0]["repositories"].append({"name": name, "summary": "Example."})
                with self.assertRaisesRegex(ValueError, "extra in catalog: " + re.escape(name)):
                    checks.compare_membership(catalog, self.repositories + [repository(name, archived=archived)])

    def test_pagination_and_authorization_with_injected_responses(self):
        first = "https://api.github.com/orgs/skill-cli/repos?type=public&per_page=100"
        second = first + "&page=2"
        opener = mock.Mock(side_effect=[
            Response(self.repositories[:1], f'<{second}>; rel="last", <{second}>; rel="next"'),
            Response(self.repositories[1:] + [repository(".github")]),
        ])
        fetched = checks.fetch_repositories("skill-cli", "test-token", opener=opener)
        checks.compare_membership(self.catalog, fetched)
        self.assertEqual(len(fetched), len(self.repositories) + 1)
        self.assertEqual([call.args[0].full_url for call in opener.call_args_list], [first, second])
        for call in opener.call_args_list:
            self.assertEqual(call.args[0].get_header("Authorization"), "Bearer test-token")
            self.assertEqual(call.kwargs, {"timeout": 30})

    def test_no_authorization_header_without_token(self):
        opener = mock.Mock(return_value=Response([]))
        self.assertEqual(checks.fetch_repositories("skill-cli", opener=opener), [])
        self.assertIsNone(opener.call_args.args[0].get_header("Authorization"))

    def test_api_failure_is_explicit(self):
        opener = mock.Mock(side_effect=URLError("unreachable"))
        with self.assertRaisesRegex(ValueError, "could not read GitHub API:.*unreachable"):
            checks.fetch_repositories("skill-cli", opener=opener)

    def test_interrupted_response_is_reported_as_api_failure(self):
        response = Response([])
        response.read = mock.Mock(side_effect=IncompleteRead(b"[", 12))
        with self.assertRaisesRegex(ValueError, "could not read GitHub API:.*IncompleteRead"):
            checks.fetch_repositories("skill-cli", opener=mock.Mock(return_value=response))

    def test_invalid_api_payloads_fail(self):
        for payload in ({"message": "error"}, [None], [{"name": "missing-flags"}]):
            with self.subTest(payload=payload):
                with self.assertRaisesRegex(ValueError, "invalid repository list"):
                    checks.fetch_repositories("skill-cli", opener=mock.Mock(return_value=Response(payload)))

    def test_pagination_rejects_external_endpoint_and_cycles(self):
        for url, message in (
            ("https://example.com/repos", "outside the repository endpoint"),
            ("https://api.github.com/orgs/skill-cli/repos?type=public&per_page=100", "repeated a page"),
        ):
            with self.subTest(url=url):
                opener = mock.Mock(return_value=Response([], f'<{url}>; rel="next"'))
                with self.assertRaisesRegex(ValueError, message):
                    checks.fetch_repositories("skill-cli", "test-token", opener=opener)
                self.assertEqual(opener.call_count, 1)


class CheckCommandTests(unittest.TestCase):
    def run_checks(self, arguments, *, api_error=None, render_status=0, validation_error=None):
        output = io.StringIO()
        with contextlib.redirect_stdout(output), mock.patch.object(
            checks.subprocess, "run", return_value=subprocess.CompletedProcess([], render_status)
        ) as run, mock.patch.object(
            checks, "fetch_repositories", side_effect=api_error, return_value=[]
        ) as fetch, mock.patch.object(
            checks, "compare_membership"
        ) as compare, mock.patch.object(
            checks, "validate_catalog", side_effect=validation_error
        ), mock.patch.dict(checks.os.environ, {"GITHUB_TOKEN": "test-token"}):
            status = checks.main(arguments)
        self.assertEqual(run.call_count, 1)
        self.assertEqual(run.call_args.args[0][-1], "--check")
        return status, output.getvalue().splitlines(), fetch, compare

    def test_success_prints_one_line_per_check_and_passes_token(self):
        status, lines, fetch, compare = self.run_checks([])
        self.assertEqual(status, 0)
        self.assertEqual(lines, ["PASS catalog validation", "PASS generated profile", "PASS repository membership"])
        fetch.assert_called_once_with("skill-cli", "test-token")
        compare.assert_called_once()

    def test_offline_skips_only_membership(self):
        status, lines, fetch, compare = self.run_checks(["--offline"])
        self.assertEqual(status, 0)
        self.assertEqual(lines, ["PASS catalog validation", "PASS generated profile", "SKIP repository membership (--offline)"])
        fetch.assert_not_called()
        compare.assert_not_called()

    def test_render_failure_does_not_prevent_membership_check(self):
        status, lines, fetch, _ = self.run_checks([], render_status=1)
        self.assertEqual(status, 1)
        self.assertTrue(lines[1].startswith("FAIL generated profile"))
        fetch.assert_called_once()

    def test_offline_still_fails_catalog_and_render_checks(self):
        status, lines, fetch, _ = self.run_checks(
            ["--offline"], render_status=1, validation_error=ValueError("invalid catalog")
        )
        self.assertEqual(status, 1)
        self.assertEqual(len(lines), 3)
        self.assertEqual(lines[0], "FAIL catalog validation: invalid catalog")
        self.assertTrue(lines[1].startswith("FAIL generated profile"))
        fetch.assert_not_called()

    def test_api_failure_returns_failure_and_clear_message(self):
        status, lines, _, _ = self.run_checks([], api_error=ValueError("could not read GitHub API: unreachable"))
        self.assertEqual(status, 1)
        self.assertEqual(len(lines), 3)
        self.assertEqual(lines[2], "FAIL repository membership: could not read GitHub API: unreachable")


